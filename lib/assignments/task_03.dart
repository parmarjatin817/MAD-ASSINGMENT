void main() {
  String day = "Monday";
  switch (day) {
    case "Monday":
      print("Start of the week!");
      break;
    case "Tuesday":
      print("Keep going!");
      break;
    case "Wednesday":
      print("Midweek check!");
      break;
    case "Thursday":
      print("Almost there!");
      break;
    case "Friday":
      print("Weekend is near!");
      break;
    case "Saturday":
      print("Enjoy the weekend!");
      break;
    case "Sunday":
      print("Rest day!");
      break;
    default:
      print("Invalid day!");
  }
}
